import { randomUUID } from 'node:crypto';
import { unzipSync, strFromU8 } from 'fflate';
import { test, expect } from '../../fixtures/api.js';

test('text editing, quota, copy, trash, restore and ZIP keep content intact', async ({ account }) => {
  const { api, workspaceId, storageId, rootId } = account;
  const base = `/v1/workspaces/${workspaceId}/storages/${storageId}`;
  const content = 'Xin chào\r\nSecond line\n';
  const created = await api.post(`${base}/nodes`, { data: { parent: { nodeId: rootId }, name: 'notes.txt', text: { content, mediaType: 'text/plain' }, requestId: randomUUID() } });
  expect(created.ok(), await created.text()).toBeTruthy();
  const node = await created.json();
  expect(node.file).toMatchObject({ type: 'FILE_TYPE_TEXT', version: '1', sizeBytes: String(Buffer.byteLength(content)) });
  expect(node.file.processing).toBeUndefined();
  const edit = { append: 'One append.\n', expectedVersion: '1', requestId: randomUUID() };
  const appended = await api.patch(`${base}/nodes/${node.id}/text`, { data: edit });
  expect(appended.ok(), await appended.text()).toBeTruthy();
  const duplicate = await api.patch(`${base}/nodes/${node.id}/text`, { data: edit });
  expect(duplicate.ok(), await duplicate.text()).toBeTruthy();
  expect(await duplicate.json()).toEqual(await appended.json());
  const text = await api.get(`${base}/nodes/${node.id}/text?include_metrics=true`);
  expect((await text.json()).content).toBe(content + edit.append);
  const quota = await api.get(`/v1/workspaces/${workspaceId}/storage-quota`);
  const usage = (await quota.json()).usedBytes;
  expect(usage).toBe(String(Buffer.byteLength(content + edit.append)));
  const tooSmall = await api.patch(`/v1/workspaces/${workspaceId}/storage-quota`, { data: { quotaBytes: '1' } });
  expect(tooSmall.status()).toBe(400);
  expect((await api.patch(`/v1/workspaces/${workspaceId}/storage-quota`, { data: { quotaBytes: usage } })).ok()).toBeTruthy();
  const exhausted = await api.patch(`${base}/nodes/${node.id}/text`, { data: { append: 'excess', requestId: randomUUID() } });
  expect(exhausted.status(), await exhausted.text()).toBe(429);
  expect((await api.patch(`/v1/workspaces/${workspaceId}/storage-quota`, { data: { quotaBytes: '10000' } })).ok()).toBeTruthy();
  const copy = await api.post(`${base}/nodes:copy`, { data: { source: { nodeId: node.id }, destinationStorageId: storageId, parent: { nodeId: rootId }, name: 'copy.txt', requestId: randomUUID() } });
  expect(copy.ok(), await copy.text()).toBeTruthy();
  const copied = await copy.json();
  const archived = await api.post(`${base}/nodes:downloadArchive`, { data: { targets: [{ nodeId: copied.id }] } });
  expect(archived.ok(), await archived.text()).toBeTruthy();
  expect(archived.headers()['content-type']).toContain('application/zip');
  const zip = unzipSync(await archived.body());
  expect(strFromU8(zip['copy.txt'])).toBe(content + edit.append);
  const trashed = await api.post(`${base}/nodes/${copied.id}:trash`, { data: { requestId: randomUUID() } });
  expect(trashed.ok(), await trashed.text()).toBeTruthy();
  const entry = await trashed.json();
  expect((await api.get(`${base}/nodes/${copied.id}`)).status()).toBe(404);
  const restored = await api.post(`${base}/trash/${entry.id}:restore`, { data: {} });
  expect(restored.ok(), await restored.text()).toBeTruthy();
  expect((await api.get(`${base}/nodes/${copied.id}/text`)).ok()).toBeTruthy();
});
